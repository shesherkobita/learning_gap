CREATE TYPE user_role AS ENUM ('teacher', 'student');

-- ---------------------------------------------------------------
-- Tables (ordered so foreign keys can be declared inline)
-- ---------------------------------------------------------------
CREATE TABLE teacher (
  teacher_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  email       VARCHAR(255) NOT NULL,
  department  VARCHAR(100),
  CONSTRAINT teacher_email_key UNIQUE (email)
);

CREATE TABLE student (
  student_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id  BIGINT NOT NULL,
  name        VARCHAR(100) NOT NULL,
  class       VARCHAR(50) NOT NULL,
  email       VARCHAR(255) NOT NULL,
  CONSTRAINT student_email_key UNIQUE (email),
  CONSTRAINT fk_student_teacher FOREIGN KEY (teacher_id) REFERENCES teacher (teacher_id)
);

CREATE TABLE topic (
  topic_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_name  VARCHAR(150) NOT NULL,
  description TEXT,
  CONSTRAINT topic_topic_name_key UNIQUE (topic_name)
);

CREATE TABLE misconception (
  misconception_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             VARCHAR(150) NOT NULL,
  description      TEXT,
  category         VARCHAR(100)
);

CREATE TABLE assessment (
  assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id    BIGINT NOT NULL,
  type          VARCHAR(50) NOT NULL,
  date          DATE NOT NULL DEFAULT CURRENT_DATE,
  score         NUMERIC(5,2),
  CONSTRAINT fk_assessment_student FOREIGN KEY (student_id)
    REFERENCES student (student_id) ON DELETE CASCADE
);
CREATE INDEX idx_assessment_student ON assessment (student_id);

CREATE TABLE question (
  question_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id  BIGINT NOT NULL,
  question_text  TEXT NOT NULL,
  difficulty     SMALLINT NOT NULL CHECK (difficulty >= 0),
  correct_answer TEXT NOT NULL,
  CONSTRAINT fk_question_assessment FOREIGN KEY (assessment_id)
    REFERENCES assessment (assessment_id) ON DELETE CASCADE
);
CREATE INDEX idx_question_assessment ON question (assessment_id);

CREATE TABLE recommendation (
  recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  misconception_id  BIGINT NOT NULL,
  practice_text     TEXT NOT NULL,
  difficulty_level  SMALLINT CHECK (difficulty_level >= 0),
  resource_link     VARCHAR(500),
  CONSTRAINT fk_recommendation_misconception FOREIGN KEY (misconception_id)
    REFERENCES misconception (misconception_id) ON DELETE CASCADE
);
CREATE INDEX idx_recommendation_misconception ON recommendation (misconception_id);

CREATE TABLE student_response (
  response_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id       BIGINT NOT NULL,
  question_id      BIGINT NOT NULL,
  topic_id         BIGINT NOT NULL,
  misconception_id BIGINT,
  answer           TEXT NOT NULL,
  is_correct       BOOLEAN NOT NULL,
  response_time    INTEGER CHECK (response_time >= 0),
  CONSTRAINT uq_student_question UNIQUE (student_id, question_id),
  CONSTRAINT fk_response_student FOREIGN KEY (student_id)
    REFERENCES student (student_id) ON DELETE CASCADE,
  CONSTRAINT fk_response_question FOREIGN KEY (question_id)
    REFERENCES question (question_id) ON DELETE CASCADE,
  CONSTRAINT fk_response_topic FOREIGN KEY (topic_id)
    REFERENCES topic (topic_id),
  CONSTRAINT fk_response_misconception FOREIGN KEY (misconception_id)
    REFERENCES misconception (misconception_id) ON DELETE SET NULL
);
CREATE INDEX idx_response_question      ON student_response (question_id);
CREATE INDEX idx_response_topic         ON student_response (topic_id);
CREATE INDEX idx_response_misconception ON student_response (misconception_id);

CREATE TABLE user_account (
  user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role          user_role NOT NULL,
  teacher_id    BIGINT,
  student_id    BIGINT,
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  failed_logins SMALLINT NOT NULL DEFAULT 0 CHECK (failed_logins >= 0),
  last_login_at TIMESTAMP,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT user_account_email_key      UNIQUE (email),
  CONSTRAINT user_account_teacher_id_key UNIQUE (teacher_id),
  CONSTRAINT user_account_student_id_key UNIQUE (student_id),
  CONSTRAINT fk_account_teacher FOREIGN KEY (teacher_id) REFERENCES teacher (teacher_id),
  CONSTRAINT fk_account_student FOREIGN KEY (student_id) REFERENCES student (student_id)
);

-- MySQL's "ON UPDATE current_timestamp()" has no direct equivalent in PostgreSQL,
-- so a trigger keeps updated_at current.
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_user_account_updated_at
  BEFORE UPDATE ON user_account
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

